// 获取当前语言
function getCurrentLanguage() {
    return localStorage.getItem('language') || 'zh';
}

// 设置语言
function setLanguage(lang) {
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en-US';
}

// 获取翻译文本
function getTranslation(key) {
    const currentLang = getCurrentLanguage();
    return i18n[currentLang][key] || key;
}

// 更新页面语言
function updatePageLanguage() {
    // 更新所有带有 data-i18n 属性的元素
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key) {
            // 检查是否有特殊属性需要翻译
            if (key.startsWith('[')) {
                const match = key.match(/\[(.*?)\](.*)/);
                if (match) {
                    const attr = match[1];
                    const attrKey = match[2];
                    element.setAttribute(attr, getTranslation(attrKey));
                }
            } else {
                element.textContent = getTranslation(key);
            }
        }
    });

    // 更新所有带有占位符的输入框
    document.querySelectorAll('input[data-i18n][placeholder], textarea[data-i18n][placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (key && key.startsWith('[placeholder]')) {
            const placeholderKey = key.replace('[placeholder]', '');
            element.placeholder = getTranslation(placeholderKey);
        }
    });
}

// 切换语言
function changeLanguage(lang) {
    if (lang && (lang === 'zh' || lang === 'en')) {
        setLanguage(lang);
        updatePageLanguage();
        updateLanguageButtons();
        // 触发自定义事件，通知其他组件语言已更改
        window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
    }
}

// 更新语言按钮状态
function updateLanguageButtons() {
    const currentLang = getCurrentLanguage();
    document.querySelectorAll('.btn-lang').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        btn.classList.toggle('active', btnLang === currentLang);
    });
}

// 初始化语言
function initLanguage() {
    // 设置初始语言
    const currentLang = getCurrentLanguage();
    setLanguage(currentLang);
    
    // 更新页面文本
    updatePageLanguage();
    
    // 更新按钮状态
    updateLanguageButtons();
    
    // 添加语言切换按钮事件监听
    document.querySelectorAll('.btn-lang').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = e.target.getAttribute('data-lang');
            changeLanguage(lang);
        });
    });
}

// 页面加载完成后初始化
document.addEventListener('DOMContentLoaded', initLanguage);

// 监听动态加载的内容
const observer = new MutationObserver(() => {
    updatePageLanguage();
});

// 观察整个文档的变化
observer.observe(document.documentElement, {
    childList: true,
    subtree: true
});
